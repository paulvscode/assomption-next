    <section class="card" id="principe">
      <h2>1. Le principe</h2>
      <p>Le site est composé de <strong>pages</strong> (présentation de l’école, inscriptions, cantine…) et d’<strong>actualités</strong> et <strong>événements</strong>. Chaque page se modifie en remplissant des cases, comme un formulaire.</p>
      <p>Quand vous cliquez sur <strong>« Enregistrer »</strong>, la modification est <strong>immédiatement visible</strong> sur le site. Il n’y a rien d’autre à faire.</p>
      <p class="tip">Le plus simple : allez sur le site, ouvrez la page à modifier, puis cliquez sur le bouton <strong>« Modifier cette page »</strong> en bas à droite de l’écran (il n’apparaît que lorsque vous êtes connecté(e)).</p>
    </section>

    <section class="card" id="modifier">
      <h2>2. Modifier une page</h2>
      <ol class="steps">
        <li>Dans le menu de gauche, cliquez sur <strong>Pages du site</strong>, puis sur la page voulue.</li>
        <li>Modifiez les cases. Les textes d’aide en gris sous chaque case expliquent où le texte apparaît.</li>
        <li>Pour vérifier le résultat avant de le publier, cliquez sur <strong>« Aperçu »</strong> : la page s’ouvre dans un nouvel onglet, sans rien publier.</li>
        <li>Cliquez sur <strong>« Enregistrer »</strong>. Un message vert confirme que c’est en ligne.</li>
      </ol>
      <p>Certaines pages contiennent des <strong>blocs</strong> (des encadrés, des membres du bureau, des documents…). Utilisez <strong>« Ajouter… »</strong> sous la liste pour en créer un, les flèches ▲ ▼ pour changer l’ordre, et la corbeille pour en retirer un.</p>
      <p>Les cases <strong>« Un point par ligne »</strong> créent une liste à puces : passez simplement à la ligne (touche Entrée) entre chaque point.</p>
      <p>Plusieurs pages ont une case <strong>« L’essentiel en bref »</strong> : 2 à 4 points clés, un par ligne, affichés dans un encadré en haut de la page pour les parents pressés.</p>
      <p class="tip">Si vous quittez la page sans enregistrer, le navigateur vous prévient pour éviter de perdre votre travail.</p>
    </section>

    <section class="card" id="anglais">
      <h2>3. Les textes en anglais</h2>
      <p>Le site existe en français et en anglais. En haut du formulaire, le bouton <strong>« Vous modifiez la version : Français / English »</strong> permet de passer d’une langue à l’autre. Le nombre affiché à côté de « English » indique les cases anglaises encore vides.</p>
      <p><strong>Pas le temps de traduire ?</strong> Laissez la case anglaise vide : le texte français s’affichera à la place sur le site anglais. Rien ne sera « cassé ».</p>
    </section>

    <section class="card" id="texte">
      <h2>4. Mettre en forme un texte</h2>
      <p>Les grandes zones de texte ont une barre d’outils : <strong>Titre</strong> et <strong>Sous-titre</strong> pour structurer, <strong>G</strong> pour le gras, <strong>• Liste</strong> pour une liste à puces, <strong>Lien</strong> pour ajouter un lien (sélectionnez d’abord les mots à transformer en lien).</p>
      <p class="tip">Vous pouvez copier-coller un texte depuis Word ou un e-mail : la mise en forme compliquée (polices, couleurs) est retirée automatiquement pour que le site reste harmonieux.</p>
    </section>

    <section class="card" id="images">
      <h2>5. Images et documents</h2>
      <ul>
        <li>Cliquez sur <strong>« Choisir une image »</strong> (ou « Choisir un fichier ») à l’endroit voulu, puis envoyez un fichier depuis votre ordinateur, ou réutilisez un fichier déjà envoyé.</li>
        <li>Les photos sont automatiquement réduites et allégées : vous pouvez envoyer directement les photos de votre téléphone. Les informations cachées (position GPS…) sont supprimées.</li>
        <li>Ajoutez une courte <strong>description</strong> sous chaque photo : elle est lue aux personnes malvoyantes.</li>
        <li>Documents acceptés : PDF, Word, Excel, OpenOffice. Préférez le <strong>PDF</strong>, lisible par tout le monde.</li>
        <li>Pour remplacer un document (ex. la liste de fournitures de l’année suivante), cliquez sur « Changer le fichier » dans la page concernée.</li>
      </ul>
      <p class="tip">Attention aux photos d’élèves : ne publiez que des photos d’enfants dont les parents ont donné leur autorisation écrite de diffusion.</p>
    </section>

    <section class="card" id="actualites">
      <h2>6. Publier une actualité ou un événement</h2>
      <ol class="steps">
        <li>Cliquez sur <strong>Actualités</strong> puis <strong>« Nouvelle actualité »</strong> (ou Événements → « Nouvel événement »).</li>
        <li>Remplissez au minimum le <strong>titre</strong> et la <strong>date</strong>. Une photo et un résumé rendent l’actualité plus attrayante.</li>
        <li>Dans le cadre <strong>Publication</strong>, choisissez « Publié » pour la mettre en ligne tout de suite, ou « Brouillon » pour la terminer plus tard.</li>
        <li>Enregistrez. Les 3 dernières actualités de l’école apparaissent sur la page d’accueil.</li>
      </ol>
      <p>Pour supprimer une actualité, ouvrez-la et cliquez sur <strong>« Mettre à la corbeille »</strong> en bas. Elle peut être récupérée depuis la <a href="/admin/corbeille">corbeille</a>.</p>
      <p>Les événements passés restent visibles dans une section « Événements passés » : inutile de les supprimer.</p>
    </section>

    <section class="card" id="annonce">
      <h2>7. Afficher une annonce urgente</h2>
      <p>Sur l’écran d’<a href="/admin">accueil</a> de l’administration, le cadre <strong>« Annonce sur la page d’accueil »</strong> permet d’afficher un bandeau coloré en haut du site en quelques secondes (fermeture pour intempéries, grève, réunion…). Pensez à le désactiver quand l’information n’est plus d’actualité.</p>
    </section>

    <section class="card" id="accueil">
      <h2>La page d’accueil</h2>
      <p>Sous la grande photo, les parents trouvent :</p>
      <ul>
        <li><strong>Accès rapide parents</strong> : les boutons vers les informations les plus demandées (inscriptions, cantine, vacances…). Modifiez-les dans <a href="/admin/pages/landing">Page d’accueil</a>.</li>
        <li><strong>La prochaine date à retenir</strong>, calculée automatiquement à partir du <a href="/admin/pages/schoolBreaks">calendrier des vacances</a> : il suffit de tenir ce calendrier à jour. Saisissez chaque période avec son nom et ses dates ; elles s’écrivent toutes seules en toutes lettres, en français et en anglais.</li>
        <li><strong>Les prochains événements</strong> de l’APEL et <strong>les dernières actualités</strong>.</li>
        <li><strong>Le mot de la direction</strong> (facultatif) : un court message signé, avec une photo.</li>
      </ul>
    </section>

    <section class="card" id="erreur">
      <h2>8. J’ai fait une erreur !</h2>
      <p>Pas de panique : <strong>chaque enregistrement garde une copie de la version précédente</strong>. Dans la page concernée, cliquez sur <strong>« Versions précédentes »</strong> (colonne de droite) et restaurez la version voulue. Les 30 dernières versions de chaque page sont conservées.</p>
    </section>

    <section class="card" id="rentree">
      <h2>9. Check-list de rentrée</h2>
      <ul class="checklist">
        <li><a href="/admin/pages/professorsPage">Équipe enseignante</a> : année scolaire, enseignants, personnel.</li>
        <li><a href="/admin/pages/backToSchool">Rentrée scolaire</a> : dates, horaires, note de rentrée, listes de fournitures.</li>
        <li><a href="/admin/pages/schoolBreaks">Calendrier des vacances</a> : ajoutez les dates de la nouvelle année (l’accueil de l’administration vous le rappelle quand il n’y a plus de date à venir).</li>
        <li><a href="/admin/pages/schoolProject">Projet d’établissement</a> : actions de l’année.</li>
        <li><a href="/admin/pages/applicationForm">Inscription</a> et <a href="/admin/pages/fees">frais de scolarité</a> : nouveaux documents.</li>
        <li><a href="/admin/pages/apelPresentation">APEL</a> et <a href="/admin/pages/ogecPresentation">OGEC</a> : composition des bureaux.</li>
      </ul>
    </section>

    <section class="card" id="securite">
      <h2>10. Sécurité</h2>
      <ul>
        <li>Chaque personne a <strong>son propre compte</strong>. Ne partagez pas votre mot de passe ; demandez plutôt un compte à l’administrateur.</li>
        <li>Sur un ordinateur partagé, cliquez toujours sur <strong>« Se déconnecter »</strong> en bas du menu.</li>
        <li>Par sécurité, vous êtes déconnecté(e) automatiquement après 4 heures sans activité.</li>
        <li>Après 5 mots de passe erronés, la connexion est bloquée 15 minutes.</li>
      </ul>
    </section>
